-- ============================================================================
--  books — MariaDB schema
--  ---------------------------------------------------------------------------
--  Mirrors the Prisma model documented in PLAN.md (Step 2.1), which targets
--  MariaDB via Prisma's `provider = "mysql"`. Use this script to provision a
--  fresh database + tables without running `prisma migrate` (e.g. for the
--  local Docker engine, or a managed MariaDB instance).
--
--  Target : MariaDB 10.5+ / 11.x (utf8mb4, InnoDB, DYNAMIC row format).
--  Run    : mariadb -u <admin> -p < db/schema.sql
--           # or, inside the dev container defined in PLAN.md Step 2.2:
--           docker compose exec -T books_db mariadb -u root -p < db/schema.sql
--
--  NOTES on Prisma fidelity (why a few columns have no DB-level default):
--   * `id` is VARCHAR(191) with NO database default. Prisma's `@default(uuid())`
--     is generated in the client, so Prisma supplies the UUID on insert. For
--     raw-SQL inserts, call MariaDB's UUID() yourself (see SAMPLE INSERTS).
--   * `createdAt` uses a DB default `CURRENT_TIMESTAMP(3)` — Prisma also emits
--     this for `@default(now())`.
--   * `updatedAt` is a PLAIN NOT NULL column with NO database default and NO
--     `ON UPDATE` clause — this is EXACTLY what Prisma emits for `@updatedAt`
--     (Prisma Client sets the value in application code on every write). Do NOT
--     add `ON UPDATE CURRENT_TIMESTAMP`: it deviates from Prisma and makes
--     `prisma migrate` regenerate the same diff on every run (see prisma#7724).
--   * Re-running this file against a populated DB will error on the ALTER TABLE
--     foreign-key steps (drop the FKs first, or run once on a clean database).
-- ============================================================================

SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS `reading_tracker_local`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `reading_tracker_local`;

-- ---------------------------------------------------------------------------
-- 2. Application runtime user  `book` / `password`
--    Create the login the Next.js app uses at runtime and grant it rights on
--    THIS database only (never global). ALL PRIVILEGES lets `prisma db push` /
--    `prisma migrate` apply DDL during development. For a locked-down runtime,
--    swap in:  GRANT SELECT, INSERT, UPDATE, DELETE ON `reading_tracker_local`.*
--    Two hosts are created: '%' for container/network access (Docker Compose)
--    and 'localhost' for local socket connections.
-- ---------------------------------------------------------------------------
CREATE USER IF NOT EXISTS 'book'@'localhost' IDENTIFIED BY 'password';
CREATE USER IF NOT EXISTS 'book'@'%'         IDENTIFIED BY 'password';

GRANT ALL PRIVILEGES ON `reading_tracker_local`.* TO 'book'@'localhost';
GRANT ALL PRIVILEGES ON `reading_tracker_local`.* TO 'book'@'%';

FLUSH PRIVILEGES;

-- ---------------------------------------------------------------------------
-- Author  (1-to-Many -> Book)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Author` (
  `id`        VARCHAR(191) NOT NULL,                    -- UUID, generated by Prisma
  `name`      VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `Author_name_key` (`name`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  ROW_FORMAT = DYNAMIC;

-- ---------------------------------------------------------------------------
-- Genre  (1-to-Many -> Book, optional)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Genre` (
  `id`        VARCHAR(191) NOT NULL,                    -- UUID, generated by Prisma
  `name`      VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `Genre_name_key` (`name`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  ROW_FORMAT = DYNAMIC;

-- ---------------------------------------------------------------------------
-- Book
--   title + authorId + ano -> composite unique (idempotent re-imports)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Book` (
  `id`                VARCHAR(191) NOT NULL,            -- UUID, generated by Prisma
  `title`             VARCHAR(191) NOT NULL,
  `numero_de_paginas` INT          NULL,                 -- totalPages  (nullable: pre-2014 rows)
  `currentPages`      INT          NOT NULL DEFAULT 0,
  `status`            ENUM('PENDING','READING','COMPLETED','WISH_LIST') NOT NULL DEFAULT 'PENDING',
  `nota_personal`     DOUBLE       NULL,                 -- rating      (decimal 0–10)
  `ano`               INT          NOT NULL,             -- readingYear (from the TAB NAME)
  `ano_publicacion`   INT          NULL,                 -- publicationYear (from the "Año" column)
  `origen`            VARCHAR(191) NULL,
  `fecha_inicio`      DATETIME(3)  NULL,
  `fecha_fin`         DATETIME(3)  NULL,
  `authorId`          VARCHAR(191) NOT NULL,
  `genreId`           VARCHAR(191) NULL,
  `createdAt`         DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`         DATETIME(3)  NOT NULL,                             -- @updatedAt: set by Prisma Client (no DB default)
  PRIMARY KEY (`id`),
  UNIQUE KEY `Book_title_authorId_readingYear_key` (`title`, `authorId`, `ano`),
  KEY `Book_authorId_fkey` (`authorId`),
  KEY `Book_genreId_fkey` (`genreId`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  ROW_FORMAT = DYNAMIC;

-- ---------------------------------------------------------------------------
-- Foreign keys  (kept as ALTER TABLE, exactly as Prisma emits "AddForeignKey")
-- ---------------------------------------------------------------------------
ALTER TABLE `Book`
  ADD CONSTRAINT `Book_authorId_fkey`
  FOREIGN KEY (`authorId`) REFERENCES `Author` (`id`)
  ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE `Book`
  ADD CONSTRAINT `Book_genreId_fkey`
  FOREIGN KEY (`genreId`) REFERENCES `Genre` (`id`)
  ON DELETE SET NULL ON UPDATE CASCADE;

